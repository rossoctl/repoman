#!/usr/bin/env bash
# Pinned-SHA footer for the two Phase 6 consumers that were deferred:
# pr-review (pr-review-fixer.sh footer) and weekly-report (appended to the
# report). Covers the 6a _meta rules: write on success, write nothing on
# failure, never overwrite a valid meta file.
set -uo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SCRIPTS="$ROOT/skills/repoman/scripts"
# shellcheck disable=SC1091
source "$SCRIPTS/program-lib.sh"

fail=0
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT
FAKE_SHA="85449beabc1234567890abcdef1234567890abcd"
PINNED="deadbeefdeadbeefdeadbeefdeadbeefdeadbeef"

check() {
  local name="$1" cond="$2"
  if eval "$cond"; then
    echo "PASS: $name"
  else
    echo "FAIL: $name"
    fail=1
  fi
}

for skill in github-pr-review github-weekly-report; do
  dir="$TMP/ok-$skill"
  mkdir -p "$dir"
  gh() { printf '%s\n' "$FAKE_SHA"; }
  sha=$(SKILL_SOURCE_REPO="rossoctl/agent-skills" REPOMAN_SKILL_DIR="$dir" \
    resolve_skill_meta "$dir" "$skill")
  check "$skill meta written" "[ \"$sha\" = \"$FAKE_SHA\" ] && [ -f \"$dir/_meta.$skill.json\" ]"
  foot=$(SKILL_SOURCE_REPO="rossoctl/agent-skills" REPOMAN_SKILL_DIR="$dir" \
    skill_attribution "$skill")
  check "$skill pinned footer" "case \"\$foot\" in *\"Generated by RepoMan $skill@${FAKE_SHA:0:7}\"*\"blob/$FAKE_SHA/skills/$skill/SKILL.md\"*) true ;; *) false ;; esac"

  dirf="$TMP/fail-$skill"
  mkdir -p "$dirf"
  gh() { return 1; }
  sha=$(SKILL_SOURCE_REPO="rossoctl/agent-skills" REPOMAN_SKILL_DIR="$dirf" \
    resolve_skill_meta "$dirf" "$skill" 2>/dev/null)
  foot=$(SKILL_SOURCE_REPO="rossoctl/agent-skills" REPOMAN_SKILL_DIR="$dirf" \
    skill_attribution "$skill" 2>/dev/null)
  check "$skill failure writes nothing" "[ -z \"$sha\" ] && [ ! -f \"$dirf/_meta.$skill.json\" ]"
  check "$skill blob/main fallback" "case \"\$foot\" in *\"blob/main/skills/$skill/SKILL.md\"*) true ;; *) false ;; esac"
  check "$skill fallback has no @sha" "case \"\$foot\" in *@*) false ;; *) true ;; esac"

  dirp="$TMP/pin-$skill"
  mkdir -p "$dirp"
  printf '{"version":"%s","source":"rossoctl/agent-skills","installed_at":"2026-01-01"}\n' \
    "$PINNED" > "$dirp/_meta.$skill.json"
  called="$TMP/called-$skill"
  : > "$called"
  gh() { echo called >> "$called"; printf '%s\n' "$FAKE_SHA"; }
  sha=$(SKILL_SOURCE_REPO="rossoctl/agent-skills" REPOMAN_SKILL_DIR="$dirp" \
    resolve_skill_meta "$dirp" "$skill")
  check "$skill existing meta kept" "[ \"$sha\" = \"$PINNED\" ] && [ ! -s \"$called\" ]"
done
unset -f gh

# Subprocess gh, so the entry points pick up the stub instead of a real call.
mkdir -p "$TMP/bin"
cat > "$TMP/bin/gh" << 'EOF'
#!/bin/sh
if [ -n "${GH_LOG:-}" ]; then
  echo "$@" >> "$GH_LOG"
fi
if [ "${GH_FAIL:-}" = "1" ]; then
  echo "rate limited" >&2
  exit 1
fi
printf '%s\n' "$GH_SHA"
EOF
chmod +x "$TMP/bin/gh"
export PATH="$TMP/bin:$PATH"
export GH_SHA="$FAKE_SHA"
export GH_LOG="$TMP/gh.log"
export SKILL_SOURCE_REPO="rossoctl/agent-skills"
: > "$GH_LOG"

export REPOMAN_SKILL_DIR="$TMP/fixer"
mkdir -p "$REPOMAN_SKILL_DIR"
foot=$(bash "$SCRIPTS/pr-review-fixer.sh" footer)
case "$foot" in
  *"Generated by RepoMan github-pr-review@${FAKE_SHA:0:7}"*"blob/$FAKE_SHA/skills/github-pr-review/SKILL.md"*)
    echo "PASS: fixer footer line" ;;
  *) echo "FAIL: fixer footer line: $foot"; fail=1 ;;
esac
check "fixer writes _meta" "[ -f \"$REPOMAN_SKILL_DIR/_meta.github-pr-review.json\" ]"
: > "$GH_LOG"
bash "$SCRIPTS/pr-review-fixer.sh" footer >/dev/null
check "fixer does not refresh a valid _meta" "[ ! -s \"$GH_LOG\" ]"

export REPOMAN_REPOS_FILE="$TMP/repos.json"
printf '[{"owner":"acme","name":"widgets"}]\n' > "$REPOMAN_REPOS_FILE"
export REPORT_PY="$TMP/report.py"
cat > "$REPORT_PY" << 'PY'
import sys
args = sys.argv[1:]
if "--output" in args:
    open(args[args.index("--output") + 1], "w").write("# Weekly\nbody\n")
else:
    sys.stdout.write("# Weekly\nbody\n")
PY
export REPOMAN_SKILL_DIR="$TMP/weekly"
mkdir -p "$REPOMAN_SKILL_DIR"
: > "$GH_LOG"
out="$TMP/report.md"
bash "$SCRIPTS/weekly-report.sh" --output "$out" >/dev/null
last=$(tail -n 1 "$out")
check "weekly report keeps its body" "grep -q '# Weekly' \"$out\""
case "$last" in
  *"Generated by RepoMan github-weekly-report@${FAKE_SHA:0:7}"*"blob/$FAKE_SHA/skills/github-weekly-report/SKILL.md"*)
    echo "PASS: weekly report ends with pinned footer" ;;
  *) echo "FAIL: weekly report ends with pinned footer: $last"; fail=1 ;;
esac
check "weekly writes its own _meta" "[ -f \"$REPOMAN_SKILL_DIR/_meta.github-weekly-report.json\" ]"
check "report.py does not add a second footer" "! grep -q 'Generated by RepoMan' \"$ROOT/skills/github-weekly-report/scripts/report.py\""

export GH_FAIL=1
export REPOMAN_SKILL_DIR="$TMP/weekly-fail"
mkdir -p "$REPOMAN_SKILL_DIR"
outf="$TMP/report-fail.md"
bash "$SCRIPTS/weekly-report.sh" --output "$outf" >/dev/null 2>&1
lastf=$(tail -n 1 "$outf")
case "$lastf" in
  *"blob/main/skills/github-weekly-report/SKILL.md"*)
    echo "PASS: weekly failure uses blob/main" ;;
  *) echo "FAIL: weekly failure uses blob/main: $lastf"; fail=1 ;;
esac
check "weekly failure writes no _meta" "[ ! -f \"$REPOMAN_SKILL_DIR/_meta.github-weekly-report.json\" ]"

[ "$fail" -eq 0 ] && echo "PASS: pr-review and weekly-report attribution" || exit 1
